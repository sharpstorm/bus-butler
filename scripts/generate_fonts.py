"""Generate the Adafruit-GFX fonts used by the UI (src/Ui/Fonts/UiFonts.*).

This does what Adafruit's `fontconvert` does (FreeType, 141 dpi, 1-bit mono
render), plus two things fontconvert can't: picking a weight on variable fonts
and remapping glyphs (the degree sign lives on '`', icons live on 'a'..'z').

Usage:
  pip install freetype-py
  python scripts/generate_fonts.py <fonts-dir>

<fonts-dir> must contain (all from github.com/google/fonts and
github.com/google/material-design-icons):
  Figtree[wght].ttf
  SpaceGrotesk[wght].ttf
  MaterialIcons-Regular.ttf
  MaterialIcons-Regular.codepoints
"""
import os
import sys

import freetype

DPI = 141
HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, '..', 'src', 'Ui', 'Fonts')

DEGREE = '`'  # glyph slot that holds the degree sign in text fonts

# Icon slots. Keep in sync with the ICON_* defines emitted into UiFonts.h.
ICONS = [
    ('a', 'SUN', 'wb_sunny'),
    ('b', 'MOON', 'nights_stay'),
    ('c', 'PARTLY', 'filter_drama'),
    ('d', 'CLOUD', 'cloud'),
    ('e', 'FOG', 'foggy'),
    ('f', 'WIND', 'air'),
    ('g', 'RAIN', 'umbrella'),
    ('h', 'STORM', 'thunderstorm'),
    ('i', 'DROP', 'water_drop'),
    ('j', 'THERMO', 'thermostat'),
    ('k', 'WARNING', 'warning'),
    ('l', 'TRAIN', 'train'),
    ('m', 'BUS', 'directions_bus'),
    ('n', 'SETTINGS', 'settings'),
    ('o', 'REFRESH', 'refresh'),
    ('p', 'BRIGHTNESS', 'brightness_6'),
    ('q', 'TIMER', 'timer'),
    ('r', 'BEDTIME', 'bedtime'),
    ('s', 'WIFI', 'wifi'),
    ('t', 'MEMORY', 'memory'),
    ('u', 'CLOCK', 'schedule'),
    ('v', 'INFO', 'info'),
    ('w', 'CHECK', 'check_circle'),
    ('x', 'MASK', 'masks'),
    ('y', 'UV', 'light_mode'),
    ('z', 'QR', 'qr_code_2'),
]

# (C name, file, point size, weight, first, last)
TEXT_FONTS = [
    ('FigClock', 'Figtree[wght].ttf', 34, 300, 0x20, 0x3A),
    ('FigTemp', 'Figtree[wght].ttf', 22, 300, 0x20, 0x60),
    ('FigMed', 'Figtree[wght].ttf', 9, 600, 0x20, 0x7E),
    ('FigSm', 'Figtree[wght].ttf', 7, 500, 0x20, 0x7E),
    ('SgSvcL', 'SpaceGrotesk[wght].ttf', 14, 700, 0x20, 0x7E),
    ('SgSvc', 'SpaceGrotesk[wght].ttf', 11, 700, 0x20, 0x7E),
    ('SgBig', 'SpaceGrotesk[wght].ttf', 17, 600, 0x20, 0x7E),
    ('SgMed', 'SpaceGrotesk[wght].ttf', 9, 600, 0x20, 0x7E),
    ('SgSm', 'SpaceGrotesk[wght].ttf', 7, 500, 0x20, 0x7E),
]
ICON_FONTS = [('IconSm', 8), ('IconMd', 11), ('IconLg', 18), ('IconXl', 26)]


def load_face(path, pt, wght=None):
    face = freetype.Face(path)
    if wght is not None:
        axes = face.get_variation_info().axes
        coords = [a.default for a in axes]
        for i, a in enumerate(axes):
            if a.tag == 'wght':
                coords[i] = wght
        face.set_var_design_coords(coords)
    face.set_char_size(pt << 6, 0, DPI, 0)
    return face


def render(face, codepoint):
    face.load_char(codepoint, freetype.FT_LOAD_TARGET_MONO)
    face.glyph.render(freetype.FT_RENDER_MODE_MONO)
    bmp = face.glyph.bitmap
    bits = []
    for y in range(bmp.rows):
        for x in range(bmp.width):
            bits.append(1 if bmp.buffer[y * bmp.pitch + x // 8] & (0x80 >> (x % 8)) else 0)
    return {
        'w': bmp.width, 'h': bmp.rows,
        'xa': face.glyph.advance.x >> 6,
        'xo': face.glyph.bitmap_left, 'yo': 1 - face.glyph.bitmap_top,
        'bits': bits,
    }


def emit_font(name, glyphs, first, last, y_advance):
    data = []
    table = []
    for code in range(first, last + 1):
        g = glyphs.get(code)
        if g is None:
            table.append((len(data), 0, 0, 0, 0, 0, chr(code)))
            continue
        bits = g['bits'] + [0] * (-len(g['bits']) % 8)
        offset = len(data)
        for i in range(0, len(bits), 8):
            data.append(int(''.join(map(str, bits[i:i + 8])), 2))
        table.append((offset, g['w'], g['h'], g['xa'], g['xo'], g['yo'], chr(code)))
    assert len(data) < 65536, name
    out = [f'static const uint8_t {name}Bitmaps[] PROGMEM = {{']
    for i in range(0, len(data), 16):
        out.append('  ' + ', '.join('0x%02X' % b for b in data[i:i + 16]) + ',')
    out.append('};\n')
    out.append(f'static const GFXglyph {name}Glyphs[] PROGMEM = {{')
    for (o, w, h, xa, xo, yo, ch) in table:
        label = 'degree' if ch == DEGREE and name not in ('FigClock',) else repr(ch)
        out.append(f'  {{{o}, {w}, {h}, {xa}, {xo}, {yo}}},  // {label}')
    out.append('};\n')
    out.append(f'const GFXfont {name} PROGMEM = {{(uint8_t *){name}Bitmaps, '
               f'(GFXglyph *){name}Glyphs, 0x{first:02X}, 0x{last:02X}, {y_advance}}};\n')
    return '\n'.join(out), len(data) + 7 * len(table)


def main():
    src = sys.argv[1]
    cpp = ['// Generated by scripts/generate_fonts.py. Do not edit by hand.',
           '// Figtree, Space Grotesk: SIL Open Font License 1.1.',
           '// Material Icons: Apache License 2.0.',
           '#include "UiFonts.h"\n']
    hdr = ['// Generated by scripts/generate_fonts.py. Do not edit by hand.',
           '#pragma once\n', '#include <Arduino_GFX_Library.h>\n',
           '// Text fonts. The degree sign is drawn by printing "`".',
           '#define DEG "`"\n']
    total = 0
    for (name, file, pt, wght, first, last) in TEXT_FONTS:
        face = load_face(os.path.join(src, file), pt, wght)
        glyphs = {}
        for code in range(first, last + 1):
            glyphs[code] = render(face, 0xB0 if chr(code) == DEGREE else code)
        body, size = emit_font(name, glyphs, first, last, face.size.height >> 6)
        cpp.append(body)
        hdr.append(f'extern const GFXfont {name};  // {file} {pt}pt w{wght}')
        total += size

    cps = {}
    for line in open(os.path.join(src, 'MaterialIcons-Regular.codepoints')):
        n, c = line.split()
        cps[n] = int(c, 16)
    hdr.append('\n// Icon fonts: print one character, e.g. ICON_SUN.')
    for (name, pt) in ICON_FONTS:
        face = load_face(os.path.join(src, 'MaterialIcons-Regular.ttf'), pt)
        glyphs = {ord(ch): render(face, cps[icon]) for (ch, _, icon) in ICONS}
        body, size = emit_font(name, glyphs, ord('a'), ord('z'), face.size.height >> 6)
        cpp.append(body)
        hdr.append(f'extern const GFXfont {name};  // Material Icons {pt}pt')
        total += size
    hdr.append('')
    for (ch, define, icon) in ICONS:
        hdr.append(f'#define ICON_{define} "{ch}"  // {icon}')
    hdr.append('')

    os.makedirs(OUT_DIR, exist_ok=True)
    open(os.path.join(OUT_DIR, 'UiFonts.cpp'), 'w').write('\n'.join(cpp))
    open(os.path.join(OUT_DIR, 'UiFonts.h'), 'w').write('\n'.join(hdr))
    print(f'Wrote UiFonts.cpp/.h, ~{total} bytes of font data')


if __name__ == '__main__':
    main()
